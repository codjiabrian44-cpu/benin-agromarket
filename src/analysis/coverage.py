def months_between_dates(d1_str: str, d2_str: str) -> int:
    """Inclusive number of calendar months between two YYYY-MM-DD strings."""
    y1, m1, _ = map(int, d1_str.split("-"))
    y2, m2, _ = map(int, d2_str.split("-"))
    return (y2 - y1) * 12 + (m2 - m1) + 1


def write_csv_and_md(
    csv_path: Path,
    md_path: Path,
    title: str,
    script_citation: str,
    headers: list[str],
    rows: list[list[Any]],
    notes: list[str] | None = None,
) -> None:
    """Write a tabular report as both CSV and GitHub-flavored Markdown."""
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(headers)
        writer.writerows(rows)

    lines: list[str] = [
        f"# {title}",
        "",
        f"*Generated by `{script_citation}` — do not edit by hand.*",
        "",
    ]
    if notes:
        for note in notes:
            lines.append(f"- {note}")
        lines.append("")

    lines.append("| " + " | ".join(headers) + " |")
    lines.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    lines.append("")

    md_path.write_text("\n".join(lines), encoding="utf-8")


def run_coverage_audit(
    prices_csv: Path = WFP_PRICES_RAW_CSV,
    markets_csv: Path = WFP_MARKETS_RAW_CSV,
    tables_dir: Path = DOCS_TABLES_DIR,
) -> dict[str, Any]:
    """Execute the full Phase 0 coverage audit and write all tables into ``docs/tables/``."""
    tables_dir.mkdir(parents=True, exist_ok=True)

    prices_sha256, prices_md5 = compute_checksums(prices_csv)
    prices_size = prices_csv.stat().st_size
    markets_sha256, markets_md5 = compute_checksums(markets_csv)
    markets_size = markets_csv.stat().st_size

    markets_meta: dict[str, dict[str, str]] = {}
    with markets_csv.open("r", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r.get("market_id", "").startswith("#"):
                continue
            markets_meta[r["market_id"]] = r

    total_rows = 0
    categories: Counter[str] = Counter()
    pricetypes: Counter[str] = Counter()
    units: Counter[str] = Counter()
    priceflags: Counter[str] = Counter()
    currencies: Counter[str] = Counter()
    admin1_set: set[str] = set()
    commodities_set: set[str] = set()
    active_markets: dict[str, dict[str, str]] = {}

    # Track series by (commodity, pricetype, unit)
    series_stats: dict[tuple[str, str, str], dict[str, Any]] = defaultdict(
        lambda: {
            "obs_all": 0,
            "markets_all": set(),
            "months_all": set(),
            "min_date_all": "9999-99-99",
            "max_date_all": "0000-00-00",
            "obs_19_26": 0,
            "markets_19_26": defaultdict(set),
        }
    )

    # Track market x commodity x pricetype x unit
    mkt_series: dict[tuple[str, str, str, str], dict[str, Any]] = defaultdict(
        lambda: {
            "obs_all": 0,
            "months_all": set(),
            "min_date_all": "9999-99-99",
            "max_date_all": "0000-00-00",
            "obs_19_26": 0,
            "months_19_26": set(),
            "min_date_19_26": "9999-99-99",
            "max_date_19_26": "0000-00-00",
            "date_price_map": {},
        }
    )

    yearly_counts: dict[tuple[str, str], Counter[str]] = defaultdict(Counter)
    yearly_markets: dict[tuple[str, str], defaultdict[str, set[str]]] = defaultdict(
        lambda: defaultdict(set)
    )

    min_global_date = "9999-99-99"
    max_global_date = "0000-00-00"

    with prices_csv.open("r", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r.get("date", "").startswith("#"):
                continue
            total_rows += 1
            dt = r["date"]
            ym = dt[:7]
            yr = dt[:4]
            c = r["commodity"]
            cat = r["category"]
            pt = r["pricetype"]
            u = r["unit"]
            pf = r["priceflag"]
            curr = r["currency"]
            mkt = r["market"]
            mid = r["market_id"]
            adm1 = r["admin1"]
            price_val = float(r["price"])

            if dt < min_global_date:
                min_global_date = dt
            if dt > max_global_date:
                max_global_date = dt

            categories[cat] += 1
            pricetypes[pt] += 1
            units[u] += 1
            priceflags[pf] += 1
            currencies[curr] += 1
            admin1_set.add(adm1)
            commodities_set.add(c)
            active_markets[mkt] = {
                "market_id": mid,
                "market": mkt,
                "admin1": adm1,
                "admin2": r["admin2"],
                "latitude": r["latitude"],
                "longitude": r["longitude"],
            }

            st = series_stats[(c, pt, u)]
            st["obs_all"] += 1
            st["markets_all"].add(mkt)
            st["months_all"].add(ym)
            if dt < st["min_date_all"]:
                st["min_date_all"] = dt
            if dt > st["max_date_all"]:
                st["max_date_all"] = dt
            if dt >= MODELING_START_DATE:
                st["obs_19_26"] += 1
                st["markets_19_26"][mkt].add(ym)

            ms = mkt_series[(c, pt, u, mkt)]
            ms["obs_all"] += 1
            ms["months_all"].add(ym)
            if dt < ms["min_date_all"]:
                ms["min_date_all"] = dt
            if dt > ms["max_date_all"]:
                ms["max_date_all"] = dt
            ms["date_price_map"][dt] = price_val
            if dt >= MODELING_START_DATE:
                ms["obs_19_26"] += 1
                ms["months_19_26"].add(ym)
                if dt < ms["min_date_19_26"]:
                    ms["min_date_19_26"] = dt
                if dt > ms["max_date_19_26"]:
                    ms["max_date_19_26"] = dt

            yearly_counts[(c, pt)][yr] += 1
            yearly_markets[(c, pt)][yr].add(mkt)

    active_market_ids = {v["market_id"] for v in active_markets.values()}
    inactive_market_ids = sorted(set(markets_meta.keys()) - active_market_ids, key=int)

    # 1. Generate raw_dataset_summary.csv & .md
    summary_rows: list[list[Any]] = [
        ["wfp_food_prices_ben.csv_size_bytes", prices_size, "Exact byte size of raw food prices CSV"],
        ["wfp_food_prices_ben.csv_sha256", prices_sha256, "SHA-256 hex digest of raw food prices CSV"],
        ["wfp_food_prices_ben.csv_md5", prices_md5, "MD5 hex digest of raw food prices CSV"],
        ["wfp_food_prices_ben.csv_data_rows", total_rows, "Total data rows (excluding 1 header row)"],
        ["wfp_markets_ben.csv_size_bytes", markets_size, "Exact byte size of raw markets metadata CSV"],
        ["wfp_markets_ben.csv_sha256", markets_sha256, "SHA-256 hex digest of raw markets metadata CSV"],
        ["wfp_markets_ben.csv_md5", markets_md5, "MD5 hex digest of raw markets metadata CSV"],
        ["wfp_markets_ben.csv_data_rows", len(markets_meta), "Total market metadata rows (excluding 1 header row)"],
        ["active_markets_in_prices", len(active_markets), "Unique markets with >=1 price observation"],
        ["inactive_markets_in_metadata", len(inactive_market_ids), "Markets in wfp_markets_ben.csv with 0 price rows"],
        ["departments_covered", len(admin1_set), "Unique Benin admin1 departments covered"],
        ["unique_commodities", len(commodities_set), "Unique commodity names in prices CSV"],
        ["unique_commodity_pricetype_unit_series", len(series_stats), "Unique (commodity, pricetype, unit) series"],
        ["global_min_date", min_global_date, "Earliest observation date in prices CSV"],
        ["global_max_date", max_global_date, "Latest observation date in prices CSV"],
        ["pricetype_retail_rows", pricetypes["Retail"], "Rows with pricetype == 'Retail'"],
        ["pricetype_wholesale_rows", pricetypes["Wholesale"], "Rows with pricetype == 'Wholesale'"],
        ["unit_kg_rows", units["KG"], "Rows with unit == 'KG'"],
        ["unit_l_rows", units["L"], "Rows with unit == 'L'"],
        ["currency_xof_rows", currencies["XOF"], "Rows with currency == 'XOF'"],
        ["priceflag_actual_rows", priceflags["actual"], "Rows with priceflag == 'actual'"],
    ]
    for cat_name, cat_cnt in sorted(categories.items(), key=lambda x: -x[1]):
        summary_rows.append([f"category_{cat_name}", cat_cnt, f"Rows in category '{cat_name}'"])

    # Add Yam vs Yam (white) overlap stats
    for mkt in ["Dantokpa", "Savalou", "Abomey", "Natitingou", "Bohicon", "Ouando", "Glazoué", "Parakou", "Djougou", "Nikki"]:
        y_map = mkt_series[("Yam", "Retail", "KG", mkt)]["date_price_map"]
        yw_map = mkt_series[("Yam (white)", "Retail", "KG", mkt)]["date_price_map"]
        overlap_dates = sorted(set(y_map.keys()) & set(yw_map.keys()))
        mean_abs_diff = (
            sum(abs(y_map[d] - yw_map[d]) for d in overlap_dates) / len(overlap_dates)
            if overlap_dates
            else 0.0
        )
        summary_rows.append([
            f"yam_vs_yam_white_overlap_{mkt}",
            f"Yam={len(y_map)}, Yam(white)={len(yw_map)}, overlap={len(overlap_dates)}, mean_abs_diff={mean_abs_diff:.1f} XOF/kg",
            f"Concurrent retail observation comparison in {mkt}",
        ])

    # Add Maize vs Maize (white) overlap stats
    for mkt in ["Dantokpa", "Parakou", "Natitingou", "Abomey"]:
        m_map = mkt_series[("Maize", "Retail", "KG", mkt)]["date_price_map"]
        mw_map = mkt_series[("Maize (white)", "Retail", "KG", mkt)]["date_price_map"]
        overlap_dates = sorted(set(m_map.keys()) & set(mw_map.keys()))
        summary_rows.append([
            f"maize_vs_maize_white_overlap_{mkt}",
            f"Maize={len(m_map)}, Maize(white)={len(mw_map)}, overlap={len(overlap_dates)}",
            f"Legacy Maize vs Maize (white) overlap in {mkt}",
        ])

    write_csv_and_md(
        csv_path=tables_dir / "raw_dataset_summary.csv",
        md_path=tables_dir / "raw_dataset_summary.md",
        title="Raw Dataset Summary & Audit Metrics (`wfp_food_prices_ben.csv` & `wfp_markets_ben.csv`)",
        script_citation="src/analysis/coverage.py",
        headers=["metric", "value", "description"],
        rows=summary_rows,
    )

    # 2. Generate coverage_by_commodity.csv & .md (Table A)
    table_a_rows: list[list[Any]] = []
    for label, comm, pt, unit in TABLE_A_SERIES_SPEC:
        st = series_stats[(comm, pt, unit)]
        exp_all = months_between_dates(st["min_date_all"], st["max_date_all"])
        uniq_all = len(st["months_all"])
        mkts_19_26 = st["markets_19_26"]
        n_active_19_26 = len(mkts_19_26)
        n_ge_60 = sum(1 for m_set in mkts_19_26.values() if len(m_set) >= TIER2_MIN_OBSERVED_MONTHS)
        n_ge_80 = sum(1 for m_set in mkts_19_26.values() if len(m_set) >= TIER1_MIN_OBSERVED_MONTHS)
        table_a_rows.append([
            label,
            comm,
            f"{pt}, {unit}",
            st["obs_all"],
            len(st["markets_all"]),
            f"{st['min_date_all']}..{st['max_date_all']}",
            f"{uniq_all} / {exp_all}",
            st["obs_19_26"],
            f"{n_ge_60} / {n_active_19_26}",
            f"{n_ge_80} / {n_active_19_26}",
        ])

    write_csv_and_md(
        csv_path=tables_dir / "coverage_by_commodity.csv",
        md_path=tables_dir / "coverage_by_commodity.md",
        title="Table A — Global Commodity Coverage Summary (`wfp_food_prices_ben.csv`)",
        script_citation="src/analysis/coverage.py",
        headers=[
            "Target / Group",
            "Commodity",
            "Pricetype & Unit",
            "Total Obs (All)",
            "Active Markets (All)",
            "Date Range (All)",
            "Unique / Expected Months (All)",
            "Obs (2019-01..2026-09)",
            "Markets >=60m (2019-26)",
            "Tier-1 Markets >=80/93m (2019-26)",
        ],
        rows=table_a_rows,
    )

    # 3. Generate yearly_observation_density.csv & .md (Table B)
    years = [str(y) for y in range(2007, 2027)]
    table_b_rows: list[list[Any]] = []
    for comm in YEARLY_TABLE_COMMODITIES:
        yc = yearly_counts[(comm, "Retail")]
        avg_07_11 = sum(yc[str(y)] for y in range(2007, 2012)) // 5
        row = [comm, avg_07_11] + [yc[str(y)] for y in range(2012, 2027)]
        table_b_rows.append(row)

    write_csv_and_md(
        csv_path=tables_dir / "yearly_observation_density.csv",
        md_path=tables_dir / "yearly_observation_density.md",
        title="Table B — Yearly Observation Density (`2007–2026`, Retail `KG`)",
        script_citation="src/analysis/coverage.py",
        headers=["Commodity (Retail, KG)", "'07-'11 (avg/yr)"] + [str(y) for y in range(2012, 2026)] + ["2026 (Jan-Sep)"],
        rows=table_b_rows,
        notes=[
            "Shows the 2017-2018 nationwide reporting hiatus (0 rows for Maize (white) and Beans (white)) and the standardized 50-market rollout from 2019-01 onward.",
        ],
    )

    # 4. Generate coverage_by_market.csv & .md (All 51 active markets across the 4 core products)
    # Sort markets with benchmark markets first, then alphabetically by admin1 and market
    benchmark_rank = {m: idx for idx, m in enumerate(BENCHMARK_MARKETS_ORDER)}
    sorted_markets = sorted(
        active_markets.values(),
        key=lambda x: (
            0 if x["market"] in benchmark_rank else 1,
            benchmark_rank.get(x["market"], 999),
            x["admin1"],
            x["market"],
        ),
    )

    mkt_cov_rows: list[list[Any]] = []
    tier1_rows: list[list[Any]] = []

    for prod in CORE_AUDIT_PRODUCTS:
        # Collect all markets for this product to sort Tier-1 list deterministically
        prod_mkt_records: list[dict[str, Any]] = []
        for m_info in sorted_markets:
            mkt = m_info["market"]
            ms = mkt_series.get((prod, "Retail", "KG", mkt))
            if not ms or ms["obs_all"] == 0:
                obs_all = 0
                exp_all = 0
                gap_all_pct = 100.0
                span_all = "-"
                obs_19 = 0
                exp_19 = 0
                gap_93_pct = 100.0
                gap_span_19_pct = 100.0
                span_19 = "-"
                tier_str = "Thin (<60m)"
            else:
                obs_all = len(ms["months_all"])
                exp_all = months_between_dates(ms["min_date_all"], ms["max_date_all"])
                gap_all_pct = (1.0 - obs_all / exp_all) * 100.0 if exp_all > 0 else 0.0
                span_all = f"{ms['min_date_all'][:7]}..{ms['max_date_all'][:7]}"

                obs_19 = len(ms["months_19_26"])
                if obs_19 > 0:
                    exp_19 = months_between_dates(ms["min_date_19_26"], ms["max_date_19_26"])
                    gap_93_pct = (1.0 - obs_19 / MODELING_TOTAL_MONTHS) * 100.0
                    gap_span_19_pct = (1.0 - obs_19 / exp_19) * 100.0 if exp_19 > 0 else 0.0
                    span_19 = f"{ms['min_date_19_26'][:7]}..{ms['max_date_19_26'][:7]}"
                else:
                    exp_19 = 0
                    gap_93_pct = 100.0
                    gap_span_19_pct = 100.0
                    span_19 = "-"
                tier_str = classify_market_tier(obs_19)

            is_benchmark = mkt in benchmark_rank
            mkt_cov_rows.append([
                prod,
                m_info["market_id"],
                mkt,
                m_info["admin1"],
                m_info["admin2"],
                "Yes" if is_benchmark else "No",
                obs_all,
                exp_all,
                f"{gap_all_pct:.1f}%",
                span_all,
                obs_19,
                MODELING_TOTAL_MONTHS,
                f"{gap_93_pct:.1f}%",
                exp_19,
                f"{gap_span_19_pct:.1f}%",
                span_19,
                tier_str,
            ])

            if obs_19 >= TIER1_MIN_OBSERVED_MONTHS:
                prod_mkt_records.append({
                    "product": prod,
                    "market_id": m_info["market_id"],
                    "market": mkt,
                    "admin1": m_info["admin1"],
                    "admin2": m_info["admin2"],
                    "obs_19": obs_19,
                    "gap_93_pct": gap_93_pct,
                    "exp_19": exp_19,
                    "gap_span_19_pct": gap_span_19_pct,
                    "span_19": span_19,
                })

        # Sort Tier-1 markets deterministically by (-obs_19, gap_span_19_pct, admin1, market)
        prod_mkt_records.sort(key=lambda x: (-x["obs_19"], x["gap_span_19_pct"], x["admin1"], x["market"]))
        for rank_idx, rec in enumerate(prod_mkt_records, start=1):
            tier1_rows.append([
                rec["product"],
                rank_idx,
                rec["market_id"],
                rec["market"],
                rec["admin1"],
                rec["admin2"],
                f"{rec['obs_19']} / {MODELING_TOTAL_MONTHS}",
                f"{rec['gap_93_pct']:.1f}%",
                f"{rec['obs_19']} / {rec['exp_19']}",
                f"{rec['gap_span_19_pct']:.1f}%",
                rec["span_19"],
            ])

    write_csv_and_md(
        csv_path=tables_dir / "coverage_by_market.csv",
        md_path=tables_dir / "coverage_by_market.md",
        title="Table C — Market-by-Market Coverage (`product × market × period`)",
        script_citation="src/analysis/coverage.py",
        headers=[
            "Product",
            "Market ID",
            "Market",
            "Admin1",
            "Admin2",
            "Benchmark19",
            "Obs (All)",
            "Exp Months (All)",
            "Gap % (All)",
            "Period (All)",
            "Obs (2019-26)",
            "Window Months (93)",
            "Gap vs 93m %",
            "Active Span Months (2019-26)",
            "Gap within Active Span %",
            "Period (2019-26)",
            "Tier (2019-26)",
        ],
        rows=mkt_cov_rows,
        notes=[
            "Distinguishes full-history coverage (`2007-2026`, which includes the 2017-2018 reporting hiatus) from the continuous modern modeling window (`2019-01..2026-09`, 93 months).",
            "`Gap vs 93m %` = `(1 - Obs_2019_2026 / 93) * 100`. `Gap within Active Span %` = `(1 - Obs_2019_2026 / Active_Span_Months_2019_2026) * 100` (accounts for markets that joined in July 2019, i.e., 87 expected months).",
        ],
    )

    write_csv_and_md(
        csv_path=tables_dir / "tier1_markets_by_product.csv",
        md_path=tables_dir / "tier1_markets_by_product.md",
        title="Tier-1 Markets (`>= 80` Observed Months in `2019-01..2026-09`) by Product",
        script_citation="src/analysis/coverage.py",
        headers=[
            "Product",
            "Rank",
            "Market ID",
            "Market",
            "Admin1",
            "Admin2",
            "Obs / 93m",
            "Gap vs 93m %",
            "Obs / Active Span",
            "Gap within Active Span %",
            "Active Period (2019-26)",
        ],
        rows=tier1_rows,
        notes=[
            f"Tier-1 threshold: `>= {TIER1_MIN_OBSERVED_MONTHS}` observed months out of `{MODELING_TOTAL_MONTHS}` in `{MODELING_START_YM}..{MODELING_END_YM}` (`>= 86.0%` completeness).",
        ],
    )

    return {
        "total_rows": total_rows,
        "active_markets_count": len(active_markets),
        "inactive_markets_count": len(inactive_market_ids),
        "tier1_counts": Counter(r[0] for r in tier1_rows),
    }


if __name__ == "__main__":
    result = run_coverage_audit()
    print(f"[OK] Generated coverage audit tables in {DOCS_TABLES_DIR}")
    print(f"     Total rows: {result['total_rows']:,}")
    print(f"     Active markets: {result['active_markets_count']}")
    print(f"     Tier-1 counts: {dict(result['tier1_counts'])}")
