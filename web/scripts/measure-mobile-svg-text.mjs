import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { loadPlaywright, startStaticMountServer } from './playwright-loader.mjs';

const distDir = path.resolve(import.meta.dirname, '..', 'dist');
const tableOutPath = path.resolve(import.meta.dirname, '..', '..', 'docs', 'tables', 'mobile_text_sizes.md');
const BASE_MOUNT = '/benin-agromarket';

const { chromium } = await loadPlaywright();
const { server, origin } = await startStaticMountServer(distDir, BASE_MOUNT);
const browser = await chromium.launch({ headless: true });

const routesToCheck = [
  { label: 'Accueil (FR)', path: `${BASE_MOUNT}/` },
  { label: 'Home (EN)', path: `${BASE_MOUNT}/en/` },
  { label: 'Explorer (FR)', path: `${BASE_MOUNT}/explorer` },
  { label: 'Explorer (EN)', path: `${BASE_MOUNT}/en/explorer` },
  { label: 'Prévisions (FR)', path: `${BASE_MOUNT}/previsions` },
  { label: 'Forecasts (EN)', path: `${BASE_MOUNT}/en/forecast` },
];

const rows = [];

try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();

  for (const r of routesToCheck) {
    await page.goto(`${origin}${r.path}`, { waitUntil: 'networkidle' });
    await page.waitForTimeout(250);

    const measured = await page.evaluate(() => {
      const results = [];
      const svgs = Array.from(document.querySelectorAll('svg'));
      for (const svg of svgs) {
        const svgStyle = getComputedStyle(svg);
        const svgRect = svg.getBoundingClientRect();
        if (
          svgStyle.display === 'none' ||
          svgStyle.visibility === 'hidden' ||
          svg.closest('[hidden]') ||
          svgRect.width <= 0 ||
          svgRect.height <= 0
        ) {
          continue;
        }
        const vbW = svg.viewBox?.baseVal?.width || svgRect.width;
        const scale = svgRect.width / vbW;
        const chartId =
          svg.id ||
          Array.from(svg.classList).find((c) => c.endsWith('-svg') || c.includes('mobile')) ||
          'svg';

        const texts = Array.from(svg.querySelectorAll('text'));
        for (const t of texts) {
          const tStyle = getComputedStyle(t);
          const tRect = t.getBoundingClientRect();
          if (
            tStyle.display === 'none' ||
            tStyle.visibility === 'hidden' ||
            tRect.width <= 0 ||
            tRect.height <= 0
          ) {
            continue;
          }
          const rawFs = parseFloat(tStyle.fontSize || '0');
          const effectivePx = rawFs * scale;
          const content = (t.textContent || '').replace(/\s+/g, ' ').trim();
          if (!content) continue;
          results.push({
            chartId,
            viewBox: svg.getAttribute('viewBox') || '',
            renderedWidthPx: Math.round(svgRect.width * 10) / 10,
            cssFontSizePx: Math.round(rawFs * 10) / 10,
            effectivePx: Math.round(effectivePx * 100) / 100,
            textClass: t.getAttribute('class') || 'axis/tick',
            sample: content,
          });
        }
      }
      return results;
    });

    for (const item of measured) {
      rows.push({ route: r.label, ...item });
      assert.ok(
        item.effectivePx >= 11.0,
        `[${r.label} / ${item.chartId}] SVG text "${item.sample}" renders at ${item.effectivePx}px (< 11px) on 390px viewport`
      );
    }
  }

  await context.close();

  // Summarize by route + chartId + text role so the markdown table is concise and complete
  const summaryMap = new Map();
  for (const row of rows) {
    const key = `${row.route}|${row.chartId}|${row.viewBox}|${row.cssFontSizePx}`;
    const existing = summaryMap.get(key);
    if (!existing) {
      summaryMap.set(key, {
        route: row.route,
        chartId: row.chartId,
        viewBox: row.viewBox,
        renderedWidthPx: row.renderedWidthPx,
        cssFontSizePx: row.cssFontSizePx,
        minEffectivePx: row.effectivePx,
        maxEffectivePx: row.effectivePx,
        count: 1,
        samples: [row.sample],
      });
    } else {
      existing.minEffectivePx = Math.min(existing.minEffectivePx, row.effectivePx);
      existing.maxEffectivePx = Math.max(existing.maxEffectivePx, row.effectivePx);
      existing.count += 1;
      if (existing.samples.length < 3 && !existing.samples.includes(row.sample)) {
        existing.samples.push(row.sample);
      }
    }
  }

  const globalMin = Math.min(...rows.map((r) => r.effectivePx));
  const lines = [
    '# Mobile SVG Text Legibility Audit (`docs/tables/mobile_text_sizes.md`)',
    '',
    '*Generated by [`web/scripts/measure-mobile-svg-text.mjs`](../../web/scripts/measure-mobile-svg-text.mjs) at `390×844` viewport — do not edit by hand.*',
    '',
    `- **Viewport Tested:** \`390×844\` (mobile < 640px threshold)`,
    `- **Visible SVG \`<text>\` Elements Measured:** \`${rows.length}\` across all 6 chart pages (FR + EN)`,
    `- **Minimum Effective Rendered Font Size:** \`${globalMin.toFixed(2)} px\` (requirement: \`>= 11.00 px\`)`,
    '',
    '| Page | Chart SVG | Mobile ViewBox | Rendered SVG Width (px) | SVG CSS Font Size (px) | Effective Min Rendered Size (px) | Text Count | Sample Labels | Status |',
    '| --- | --- | --- | ---: | ---: | ---: | ---: | --- | --- |',
  ];

  for (const s of summaryMap.values()) {
    const safeSamples = s.samples.join(', ').replace(/\|/g, '\\|');
    const status = s.minEffectivePx >= 11.0 ? 'PASS' : 'FAIL';
    lines.push(
      `| ${s.route} | \`${s.chartId}\` | \`${s.viewBox}\` | ${s.renderedWidthPx.toFixed(1)} | ${s.cssFontSizePx.toFixed(1)} | **${s.minEffectivePx.toFixed(2)}** | ${s.count} | ${safeSamples} | ${status} |`
    );
  }
  lines.push('');

  fs.mkdirSync(path.dirname(tableOutPath), { recursive: true });
  fs.writeFileSync(tableOutPath, lines.join('\n'), 'utf8');

  console.log(
    `[Mobile Text Sizes Test] PASS: Measured ${rows.length} visible SVG <text> elements at 390px; min effective size = ${globalMin.toFixed(2)}px (>= 11px). Saved docs/tables/mobile_text_sizes.md.`
  );
} finally {
  await browser.close();
  server.close();
}
